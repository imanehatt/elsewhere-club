// Generates supabase/seed.sql from src/lib/demo-trips.ts  (run: node scripts/make-seed.mjs)
import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { stripTypeScriptTypes } from "node:module";

const js = stripTypeScriptTypes(readFileSync("src/lib/demo-trips.ts", "utf8"));
const tmp = "/tmp/demo-trips.mjs";
writeFileSync(tmp, js);
const { demoTrips } = await import(pathToFileURL(tmp).href);

const JSON_COLS = new Set(["highlights", "itinerary", "included", "excluded", "stays", "faqs", "gallery"]);
const lit = (k, v) => {
  if (v === null || v === undefined) return "null";
  if (JSON_COLS.has(k)) return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  if (typeof v === "boolean" || typeof v === "number") return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};

let sql = "-- Starter trips. Run after schema.sql. Re-running OVERWRITES these two trips with the starter content.\n-- Generated by scripts/make-seed.mjs\n\n";
for (const t of demoTrips) {
  const cols = Object.keys(t).filter((k) => k !== "id");
  sql += `insert into public.trips (${cols.join(", ")})\nvalues (${cols.map((k) => lit(k, t[k])).join(", ")})\non conflict (slug) do update set ${cols.filter((k) => k !== "slug").map((k) => `${k} = excluded.${k}`).join(", ")};\n\n`;
}
writeFileSync("supabase/seed.sql", sql);
console.log("Wrote supabase/seed.sql with", demoTrips.length, "trips");
